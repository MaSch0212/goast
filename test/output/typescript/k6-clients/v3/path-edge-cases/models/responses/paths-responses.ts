type OverlapTemplatedStatusCodes =
  | (200)
  | (401)
  | (403)
  | (500);
/**
 * Response model for operation overlapTemplated
 */
export type OverlapTemplatedApiResponse<TStatus extends OverlapTemplatedStatusCodes = OverlapTemplatedStatusCodes> = (
    | ((Omit<Response, 'json'>) & ({
          status: 200;
          json(): never;
          json(selector: string): JSONValue;
        }))
    | ((Omit<Response, 'json'>) & ({
          status: 401;
          json(): never;
          json(selector: string): JSONValue;
        }))
    | ((Omit<Response, 'json'>) & ({
          status: 403;
          json(): never;
          json(selector: string): JSONValue;
        }))
    | ((Omit<Response, 'json'>) & ({
          status: 500;
          json(): never;
          json(selector: string): JSONValue;
        }))) & ({
      status: TStatus;
    });

