import {
  type ApiEndpoint,
  type ApiParameter,
  type ApiSchema,
  type AppendValue,
  builderTemplate as s,
  resolveAnyOfAndAllOf,
  SourceBuilder,
  toCasing,
} from '@goast/core';

import { cs } from '../../../ast/index.ts';
import type { CSharpFileBuilder } from '../../../file-builder.ts';
import { toCSharpStringLiteral } from '../../../utils.ts';
import {
  getContentBodyType,
  getTypeUsage,
  isMultipartMediaType,
  toIdentifier,
  UniqueNames,
  withNullable,
} from './endpoint-helpers.ts';
import type { CSharpServerContext } from './server-config.ts';

type Builder = CSharpFileBuilder;
type Reference = cs.Reference<SourceBuilder>;

/** Where the value of a handler parameter comes from on the wire. */
export type ParameterSource = 'path' | 'query' | 'header' | 'cookie' | 'body' | 'form';

/**
 * How a framework obtains the value of a handler parameter.
 *
 * - `bound`: the framework binds a value of `actionType` to a parameter named `actionName` (with whatever binding
 *   attribute it uses for `source` and the wire name); `convert(actionName)` turns it into the handler value. When
 *   `convert` is `null` the bound value is the handler value.
 * - `request`: nothing is bound by the framework; `convert(request, cancellationToken)` reads the handler value
 *   from the `HttpRequest` expression. The expression may contain `await`.
 */
export type ParameterBinding =
  | {
      kind: 'bound';
      actionName: string;
      actionType: Reference;
      convert: ((actionName: string) => AppendValue<Builder>) | null;
    }
  | {
      kind: 'request';
      convert: (request: string, cancellationToken: string) => AppendValue<Builder>;
    };

/**
 * One parameter of an endpoint's handler method, with everything a server generator needs to declare it, bind it and
 * pass it on.
 */
export type ParameterPlan = {
  /** The spec parameter (a synthetic one for a request body and each multipart part). */
  parameter: ApiParameter;
  source: ParameterSource;
  /** The name on the wire: the parameter name, or the multipart part name. Empty for a request body. */
  wireName: string;
  /** The C# name of the handler parameter, unique within the endpoint. */
  name: string;
  /** The C# name of the variable holding the converted value (`name` unless the binding converts). */
  valueName: string;
  /** The type of the handler parameter. Nullable if the parameter is optional. */
  type: Reference;
  required: boolean;
  description: string | undefined;
  /** Whether this is a multipart part that is a file (or a list of files). */
  isFile: boolean;
  binding: ParameterBinding;
};

export type ParameterOptions = {
  /** The namespace of the generated `ApiRequestSupport` class the conversions call. */
  supportNamespace: string;
};

/** Parameters the spec says an implementation must ignore: they are set by the framework. */
const ignoredHeaders = new Set(['accept', 'content-type', 'authorization']);

/** The `HttpRequest` extension surface the conversions call, generated by `buildApiRequestSupportClass`. */
export const apiRequestSupportName = 'ApiRequestSupport';

/** The exception the conversions throw for an unbindable request, generated by `buildApiRequestExceptionClass`. */
export const apiRequestExceptionName = 'ApiRequestException';

const nativeScalarNames = new Set(['string', 'bool', 'int', 'long', 'float', 'double', 'decimal']);

const formFile = cs.reference.factory('IFormFile', 'Microsoft.AspNetCore.Http');
const formFileCollection = cs.reference.factory('IFormFileCollection', 'Microsoft.AspNetCore.Http');

/**
 * Collects the parameters of the handler method of an endpoint: the path, query, header and cookie parameters in
 * declaration order, followed by the request body (or, for `multipart/form-data`, one parameter per part).
 *
 * Optional parameters are nullable unless the schema has a default that C# can express as a constant. Scalars that
 * the framework converts correctly on its own (`string`, numbers, `bool`) are bound natively; everything else
 * (enums, dates, GUIDs, arrays, objects, cookies, bodies) is bound raw and converted by `ApiRequestSupport`, so
 * the wire format follows the spec rather than the framework's conventions.
 */
export function getEndpointParameters(
  ctx: CSharpServerContext,
  endpoint: ApiEndpoint,
  options: ParameterOptions,
): ParameterPlan[] {
  const names = new UniqueNames(['cancellationToken']);
  const plans: ParameterPlan[] = [];
  const support = cs.reference.factory(apiRequestSupportName, options.supportNamespace);
  const exception = cs.reference.factory(apiRequestExceptionName, options.supportNamespace);

  for (const parameter of endpoint.parameters) {
    if (
      parameter.target !== 'path' &&
      parameter.target !== 'query' &&
      parameter.target !== 'header' &&
      parameter.target !== 'cookie'
    ) {
      continue;
    }
    if (parameter.target === 'header' && ignoredHeaders.has(parameter.name.toLowerCase())) continue;
    plans.push(getParameterPlan(ctx, parameter, parameter.target, parameter.name, names, support, exception));
  }

  if (endpoint.requestBody) {
    const content = endpoint.requestBody.content[0];
    const required = endpoint.requestBody.required;
    if (content && isMultipartMediaType(content.type)) {
      let schema = content.schema;
      if (schema && schema.kind === 'object') {
        schema = resolveAnyOfAndAllOf(schema, true) ?? schema;
        for (const [name, property] of (schema.properties ?? new Map()).entries()) {
          plans.push(
            getParameterPlan(
              ctx,
              createParameter(
                `multipart-${name}`,
                name,
                'body',
                property.schema,
                schema.required.has(name),
                property.schema.description,
              ),
              'form',
              name,
              names,
              support,
              exception,
            ),
          );
        }
      }
    } else if (content) {
      plans.push(getBodyPlan(ctx, endpoint, names, support));
    } else if (required) {
      // A body without any declared content cannot be typed.
    }
  }

  return plans;
}

function createParameter(
  id: string,
  name: string,
  target: ApiParameter['target'],
  schema: ApiSchema | undefined,
  required: boolean,
  description: string | undefined,
): ApiParameter {
  return {
    // eslint-disable-next-line @typescript-eslint/no-non-null-assertion
    $src: undefined!,
    $ref: undefined,
    id,
    name,
    target,
    schema,
    required,
    description,
    allowEmptyValue: undefined,
    allowReserved: undefined,
    deprecated: false,
    explode: undefined,
    style: undefined,
  };
}

function getBodyPlan(
  ctx: CSharpServerContext,
  endpoint: ApiEndpoint,
  names: UniqueNames,
  support: cs.ReferenceFactory,
): ParameterPlan {
  const requestBody = endpoint.requestBody!;
  const content = requestBody.content[0];
  const required = requestBody.required;
  const type = withNullable(getContentBodyType(ctx, content), required ? false : true);
  const nonNull = withNullable(type, false);
  const name = names.next('body');
  const parameter = createParameter('body', name, 'body', content.schema, required, requestBody.description);

  return {
    parameter,
    source: 'body',
    wireName: '',
    name,
    valueName: name,
    type,
    required,
    description: requestBody.description?.trim() || undefined,
    isFile: false,
    binding: {
      kind: 'request',
      convert: (request, cancellationToken) =>
        s<Builder>`(${type})(await ${support()}.ReadBodyAsync(${request}, typeof(${nonNull}), ${String(required)}, ${cancellationToken}))${required ? '!' : ''}`,
    },
  };
}

function getParameterPlan(
  ctx: CSharpServerContext,
  parameter: ApiParameter,
  source: Exclude<ParameterSource, 'body'>,
  wireName: string,
  names: UniqueNames,
  support: cs.ReferenceFactory,
  exception: cs.ReferenceFactory,
): ParameterPlan {
  const schema = parameter.schema;
  const fallback = getDefaultLiteral(schema, getTypeUsage(ctx, schema, false));
  const nullable = !parameter.required && fallback === undefined ? true : undefined;
  const type = getTypeUsage(ctx, schema, nullable);
  const nonNull = withNullable(type, false);
  const name = names.next(toIdentifier(toCasing(parameter.name, ctx.config.parameterNameCasing), 'parameter'));

  const base = {
    parameter,
    source,
    wireName,
    name,
    type,
    required: parameter.required,
    description: parameter.description?.trim() || undefined,
  };

  const optional = !parameter.required;
  const isFile = source === 'form' && isFileSchema(schema);
  const isFileList = source === 'form' && schema?.kind === 'array' && isFileSchema(schema.items);

  // Files
  if (isFile || isFileList) {
    const actionType = isFileList ? formFileCollection({ nullable: optional }) : formFile({ nullable: optional });
    return {
      ...base,
      isFile: true,
      valueName: names.next(`${name}Value`),
      binding: {
        kind: 'bound',
        actionName: name,
        actionType,
        convert: (action) =>
          isFileList
            ? s<Builder>`${support()}.OpenReadStreams(${action}, ${String(!optional)})${optional ? '' : '!'}`
            : s<Builder>`${support()}.OpenReadStream(${action})${optional ? '' : '!'}`,
      },
    };
  }

  const style = parameter.style ?? (source === 'path' || source === 'header' ? 'simple' : 'form');
  const explode = parameter.explode ?? style === 'form';
  const bang = parameter.required ? '!' : '';
  // ASP.NET Core leaves an encoded slash (`%2F`) of a path segment encoded in the route value.
  const raw = (action: string): AppendValue<Builder> =>
    source === 'path' ? s<Builder>`${support()}.DecodePathSegment(${action})` : action;

  // Arrays
  if (schema?.kind === 'array') {
    const item = type.generics[0] ?? cs.refs.systemTextJson.jsonElement({ nullable: true });
    const exploded = (source === 'query' || source === 'form') && explode;
    if (source === 'cookie') {
      return {
        ...base,
        isFile: false,
        valueName: name,
        binding: {
          kind: 'request',
          convert: (request) =>
            s<Builder>`${support()}.ParseDelimitedList<${item}>(${request}.Cookies[${toCSharpStringLiteral(wireName)}], ",")${bang}`,
        },
      };
    }
    if (exploded) {
      return {
        ...base,
        isFile: false,
        valueName: names.next(`${name}Value`),
        binding: {
          kind: 'bound',
          actionName: name,
          actionType: cs.reference.array(cs.refs.system.string(), { nullable: optional }),
          convert: (action) =>
            s<Builder>`${support()}.ParseList<${item}>(${action}, ${String(parameter.required)})${bang}`,
        },
      };
    }

    const delimiter = style === 'spaceDelimited' ? ' ' : style === 'pipeDelimited' ? '|' : ',';
    return {
      ...base,
      isFile: false,
      valueName: names.next(`${name}Value`),
      binding: {
        kind: 'bound',
        actionName: name,
        actionType: cs.refs.system.string({ nullable: optional }),
        convert:
          source === 'path' && (style === 'label' || style === 'matrix')
            ? (action) =>
                s<Builder>`${support()}.ParsePathList<${item}>(${raw(action)}, ${toCSharpStringLiteral(style)}, ${String(explode)}, ${toCSharpStringLiteral(wireName)})${bang}`
            : (action) =>
                s<Builder>`${support()}.ParseDelimitedList<${item}>(${raw(action)}, ${toCSharpStringLiteral(delimiter)})${bang}`,
      },
    };
  }

  const isScalar =
    schema !== undefined &&
    (schema.kind === 'string' || schema.kind === 'integer' || schema.kind === 'number' || schema.kind === 'boolean');

  // Objects in a query string are assembled from several keys.
  if (source === 'query' && !isScalar) {
    return {
      ...base,
      isFile: false,
      valueName: name,
      binding: {
        kind: 'request',
        convert: (request) =>
          s<Builder>`(${type})${support()}.ReadQueryObject(${request}, typeof(${nonNull}), ${toCSharpStringLiteral(wireName)}, ${toCSharpStringLiteral(style)}, ${String(explode)})${bang}`,
      },
    };
  }

  // Cookies are not bound by the framework.
  if (source === 'cookie') {
    return {
      ...base,
      isFile: false,
      valueName: name,
      binding: {
        kind: 'request',
        convert: (request) =>
          s<Builder>`(${type})${support()}.ParseValue(${request}.Cookies[${toCSharpStringLiteral(wireName)}], typeof(${nonNull}))${bang}`,
      },
    };
  }

  // Scalars the framework binds correctly. A required value type is bound as nullable: the framework would silently
  // pass `default` for a missing value, where the contract demands a rejected request.
  if (isScalar && isNativeScalar(type) && !(source === 'path' && (style === 'label' || style === 'matrix'))) {
    const rejectMissing = fallback === undefined && parameter.required && nonNull.name !== 'string';
    const decodes = source === 'path' && nonNull.name === 'string';
    const converts = fallback !== undefined || rejectMissing || decodes;
    return {
      ...base,
      isFile: false,
      valueName: converts ? names.next(`${name}Value`) : name,
      binding: {
        kind: 'bound',
        actionName: name,
        actionType: converts && !decodes ? withNullable(type, true) : type,
        convert: !converts
          ? null
          : decodes
            ? (action) => raw(action)
            : fallback !== undefined
              ? (action) => s<Builder>`${action} ?? ${fallback}`
              : (action) =>
                  s<Builder>`${action} ?? throw new ${exception()}(${toCSharpStringLiteral(`The ${source} parameter '${wireName}' is required.`)})`,
      },
    };
  }

  // Everything else is bound as a string and converted from its wire form.
  const prefixed = source === 'path' && (style === 'label' || style === 'matrix');
  return {
    ...base,
    isFile: false,
    valueName: names.next(`${name}Value`),
    binding: {
      kind: 'bound',
      actionName: name,
      actionType: cs.refs.system.string({ nullable: optional }),
      convert: prefixed
        ? (action) =>
            s<Builder>`(${type})${support()}.ParsePathValue(${raw(action)}, typeof(${nonNull}), ${toCSharpStringLiteral(style)}, ${toCSharpStringLiteral(wireName)})${bang}`
        : (action) => s<Builder>`(${type})${support()}.ParseValue(${raw(action)}, typeof(${nonNull}))${bang}`,
    },
  };
}

/** Whether the framework converts a bound value of this type from a string on its own, without surprises. */
function isNativeScalar(type: Reference): boolean {
  return type.namespace === null && type.arrayOf === null && nativeScalarNames.has(type.name);
}

/** Whether a schema is a file: a `binary` string. */
function isFileSchema(schema: ApiSchema | undefined): boolean {
  return schema?.kind === 'string' && schema.format === 'binary';
}

/**
 * The C# literal for the default of a schema, for the plain scalar types only (`string`, `bool`, `int`, `long`,
 * `float`, `double`, `decimal`). `undefined` if there is no default or C# cannot express it as a constant.
 */
export function getDefaultLiteral(schema: ApiSchema | undefined, type: Reference): string | undefined {
  const value = schema?.default;
  if (value === undefined || value === null || !isNativeScalar(type) || schema?.enum?.length) return undefined;

  switch (type.name) {
    case 'string':
      return typeof value === 'string' ? toCSharpStringLiteral(value) : undefined;
    case 'bool':
      return typeof value === 'boolean' ? String(value) : undefined;
    case 'int':
      return typeof value === 'number' && Number.isSafeInteger(value) && Math.abs(value) <= 2147483647
        ? String(value)
        : undefined;
    case 'long':
      return typeof value === 'number' && Number.isSafeInteger(value) ? `${value}L` : undefined;
    case 'float':
      return typeof value === 'number' && Number.isFinite(value) ? `${value}f` : undefined;
    case 'double':
      return typeof value === 'number' && Number.isFinite(value) ? `${value}d` : undefined;
    case 'decimal':
      return typeof value === 'number' && Number.isFinite(value) ? `${value}m` : undefined;
    default:
      return undefined;
  }
}

/**
 * The abstract handler method every server generator declares for an endpoint:
 * `Task<<Endpoint>Result> <Endpoint>Async(<params>, CancellationToken cancellationToken)`.
 */
export function getHandlerMethod(
  name: string,
  plans: readonly ParameterPlan[],
  resultType: Reference,
  options: { doc: string | undefined; accessModifier?: cs.AccessModifier },
): cs.Method<Builder> {
  return cs.method<Builder>(name, {
    doc: cs.doc(options.doc || null),
    accessModifier: options.accessModifier ?? 'public',
    abstract: true,
    returnType: cs.refs.system.taskOf([resultType]),
    parameters: [
      ...plans.map((plan) => cs.parameter<Builder>(plan.name, plan.type, { description: plan.description })),
      cs.parameter<Builder>('cancellationToken', cs.refs.system.cancellationToken(), {
        description: 'Signals that the request was aborted.',
      }),
    ],
  });
}
