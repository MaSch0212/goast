import { describe, expect, it } from 'vitest';

import { csClass } from './ast/nodes/class.ts';
import { csProperty } from './ast/nodes/property.ts';
import { csReference } from './ast/nodes/reference.ts';
import { type CSharpGeneratorConfig, defaultCSharpGeneratorConfig } from './config.ts';
import { CSharpFileBuilder } from './file-builder.ts';

// A fixed newLine keeps the expectations below host-independent.
const config = (overrides: Partial<CSharpGeneratorConfig> = {}) =>
  ({ ...defaultCSharpGeneratorConfig, newLine: '\n', ...overrides }) as CSharpGeneratorConfig;

describe('CSharpFileBuilder', () => {
  it('should write the header, file-scoped namespace and body', () => {
    const builder = new CSharpFileBuilder('Acme.Models', config());
    builder.append(csClass('Foo', { accessModifier: 'public' }));
    expect(builder.toString()).toBe(
      '// <auto-generated/>\n#nullable enable\n\nnamespace Acme.Models;\n\npublic class Foo\n{\n}\n',
    );
  });

  it('should write sorted usings of the written references', () => {
    const builder = new CSharpFileBuilder('Acme.Models', config());
    builder.append(
      csClass('Foo', {
        accessModifier: 'public',
        members: [
          csProperty('Id', { type: csReference('Guid', 'System'), accessModifier: 'public' }),
          csProperty('Tags', {
            type: csReference('List', 'System.Collections.Generic', { generics: [csReference('Tag', 'Acme.Other')] }),
            accessModifier: 'public',
          }),
          csProperty('Json', { type: csReference('JsonElement', 'System.Text.Json'), accessModifier: 'public' }),
        ],
      }),
    );
    expect(builder.toString()).toBe(
      [
        '// <auto-generated/>',
        '#nullable enable',
        '',
        'using System;',
        'using System.Collections.Generic;',
        'using System.Text.Json;',
        'using Acme.Other;',
        '',
        'namespace Acme.Models;',
        '',
        'public class Foo',
        '{',
        '    public Guid Id { get; set; }',
        '    public List<Tag> Tags { get; set; }',
        '    public JsonElement Json { get; set; }',
        '}',
        '',
      ].join('\n'),
    );
  });

  it('should skip global usings and the own namespace and its parents', () => {
    const builder = new CSharpFileBuilder('Acme.Api.Models', config({ globalUsings: ['System'] }));
    builder.append(
      csProperty('A', { type: csReference('Guid', 'System') }),
      csProperty('B', { type: csReference('B', 'Acme.Api.Models') }),
      csProperty('C', { type: csReference('C', 'Acme.Api') }),
      csProperty('D', { type: csReference('D', 'Acme.Api.Clients') }),
    );
    expect(builder.usings.usings).toEqual(['Acme.Api.Clients']);
  });

  it('should write no namespace declaration if none is set', () => {
    const builder = new CSharpFileBuilder(undefined, config());
    builder.append(csClass('Foo'));
    expect(builder.toString()).toBe('// <auto-generated/>\n#nullable enable\n\nclass Foo\n{\n}\n');
  });

  it('should only write the body without padding', () => {
    const builder = new CSharpFileBuilder('Acme', config());
    builder.append(csProperty('A', { type: csReference('Guid', 'System') }));
    expect(builder.toString(false)).toBe('Guid A { get; set; }\n');
  });

  it('should add usings explicitly', () => {
    const builder = new CSharpFileBuilder('Acme', config());
    builder.addUsing('System.Linq').addUsing(undefined);
    expect(builder.usings.usings).toEqual(['System.Linq']);
  });

  it('should clear content and usings', () => {
    const builder = new CSharpFileBuilder('Acme', config());
    builder.append(csProperty('A', { type: csReference('Guid', 'System') }));
    builder.clear();
    expect(builder.toString(false)).toBe('');
    expect(builder.usings.hasUsings).toBe(false);
  });

  it('should fall back to the default config', () => {
    const builder = new CSharpFileBuilder('Acme');
    expect(builder.options.rootNamespace).toBe('OpenApi.Generated');
  });
});
