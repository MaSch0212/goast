import { type AppendParam, type AppendValue, isAppendValue, SourceBuilder, writeGeneratedFile } from '@goast/core';

import { CsNode } from './ast/node.ts';
import { type CSharpGeneratorConfig, defaultCSharpGeneratorConfig } from './config.ts';
import { UsingCollection } from './using-collection.ts';

export type CSharpAppends<TAdditionalAppends> = CsNode<CSharpFileBuilder> | TAdditionalAppends;
export type CSharpAppendParam<TBuilder extends CSharpFileBuilder, TAdditionalAppends> = AppendParam<
  TBuilder,
  CSharpAppends<TAdditionalAppends>
>;

export function isCSharpAppendValue<TBuilder extends CSharpFileBuilder>(
  value: unknown,
): value is AppendValue<TBuilder> {
  return isAppendValue(value) || value instanceof CsNode;
}

export class CSharpFileBuilder<TAdditionalAppends = never> extends SourceBuilder<CSharpAppends<TAdditionalAppends>> {
  public readonly namespace: string | undefined;
  public readonly usings: UsingCollection;

  public override get options(): CSharpGeneratorConfig {
    return super.options as CSharpGeneratorConfig;
  }

  constructor(namespace?: string, options?: CSharpGeneratorConfig) {
    super(options ?? defaultCSharpGeneratorConfig);
    this.namespace = namespace;
    this.usings = new UsingCollection({ globalUsings: this.options.globalUsings, namespace });
  }

  public addUsing(namespace?: string): this {
    if (namespace !== undefined) {
      this.usings.addUsing(namespace);
    }
    return this;
  }

  public override clear(): void {
    super.clear();
    this.usings.clear();
  }

  /**
   * Renders the complete file: the `// <auto-generated/>` header, `#nullable enable`, the `using` directives, the
   * file-scoped namespace and the body.
   * @param addPadding If `false`, only the body is rendered (without header, usings and namespace).
   */
  public override toString(addPadding: boolean = true): string {
    if (!addPadding) {
      return super.toString();
    }

    return new SourceBuilder(this.options)
      .appendLine('// <auto-generated/>')
      .appendLine('#nullable enable')
      .appendLine()
      .append((builder) => this.usings.writeTo(builder))
      .ensurePreviousLineEmpty()
      .if(this.namespace !== undefined, (builder) => builder.appendLine(`namespace ${this.namespace};`).appendLine())
      .append(super.toString())
      .ensureCurrentLineEmpty()
      .toString();
  }

  public writeToFile(filePath: string) {
    writeGeneratedFile(this.options, filePath, this.toString());
  }

  protected override appendSingle(value: CSharpAppendParam<this, TAdditionalAppends>): void {
    super.appendSingle(value);
    if (value instanceof CsNode) {
      value.write(this);
    }
  }
}
