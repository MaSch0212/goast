import type {
  ApiSchema,
  DefaultGenerationProviderConfig,
  OpenApiSchemasGenerationProviderContext,
  SourceBuilder,
} from '@goast/core';

import type { go } from '../../ast/index.ts';
import { defaultGoGeneratorConfig, type GoGeneratorConfig } from '../../config.ts';
import type { GoPackageInfo } from '../file-generator.ts';

/**
 * The configuration of the `GoModelsGenerator`. It extends the common Go generator configuration with the
 * model-specific options declared below.
 *
 * The common options are declared on `GoGeneratorConfig`. Their effect on the generated models is:
 * - `outputDir`: The root directory of the generated code. The models are written to `{outputDir}/{packagePath}`.
 *   Default `'generated'`.
 * - `clearOutputDir`: Empties `outputDir` once before any file is written, so it also removes files written by other
 *   generators. Default `true`.
 * - `indent`: The indentation of the generated Go code. Default tabs (`{ type: 'tabs' }`), which is what `gofmt` uses.
 * - `newLine`: The line separator of the generated files. Default the line separator of the platform.
 * - `modulePath`: The module path of the generated code. The import path of the models is `modulePath` joined with
 *   `packagePath`, which other generated packages such as the servers use to import them. Default
 *   `'example.com/generated'`.
 * - `initialisms`: Words written in all caps in the exported names of types, fields and enum constants, so `PetId`
 *   becomes `PetID`. Default `defaultGoInitialisms`.
 * - `addGeneratedHeader`: Whether each model file starts with the `// Code generated by gOAst. DO NOT EDIT.` comment.
 *   Default `true`.
 * - `includeSourceInDocs`: Adds the source document path to the doc comments of the generated types and fields.
 *   Default `false`.
 * @see defaultGoModelsGeneratorConfig
 */
export type GoModelsGeneratorConfig = GoGeneratorConfig & {
  /**
   * The directory of the package for the models, relative to the output directory and to `modulePath`. Every model is
   * declared in this package, and the servers generator writes into the same package by default.
   * @default 'api'
   */
  packagePath: string;

  /**
   * The name of the package for the models, used in its `package` clause. Derived from the last segment of
   * `packagePath` (or of `modulePath` if `packagePath` is empty) if not set.
   */
  packageName?: string;

  /**
   * Determines how `oneOf` schemas should be treated. Go has no union types, so either way the result is one struct.
   * - `treat-as-any-of`: Merge the properties of all branches, each optional.
   * - `treat-as-all-of`: Merge the properties of all branches, keeping which ones are required.
   * @default 'treat-as-any-of'
   */
  oneOfBehavior: 'treat-as-any-of' | 'treat-as-all-of';

  /**
   * Determines how schemas of type `object` without properties should be treated. Object schemas that allow additional
   * properties always become a `map[string]T`, regardless of this setting.
   * - `use-any`: Use `any` for empty object schemas. No struct is generated for them.
   * - `generate-empty-struct`: Generate an empty struct for empty object schemas.
   * @default 'generate-empty-struct'
   */
  emptyObjectTypeBehavior: 'use-any' | 'generate-empty-struct';

  /**
   * Whether to generate an `IsValid` method for enum types, which reports whether a value is one of the enum values.
   * When `false`, enum types only get their type declaration and constants.
   * @default true
   */
  addEnumValidation: boolean;
};

/**
 * The default configuration of the `GoModelsGenerator`. Options passed to the generator are merged on top of these.
 * It includes the common Go defaults from `defaultGoGeneratorConfig`.
 * @see GoModelsGeneratorConfig
 */
export const defaultGoModelsGeneratorConfig: DefaultGenerationProviderConfig<GoModelsGeneratorConfig> = {
  ...defaultGoGeneratorConfig,

  packagePath: 'api',
  oneOfBehavior: 'treat-as-any-of',
  emptyObjectTypeBehavior: 'generate-empty-struct',
  addEnumValidation: true,
};

/**
 * The input of the `GoModelsGenerator`. The generator does not use any input data, so this type has no properties.
 */
export type GoModelsGeneratorInput = {};

/**
 * The output of the `GoModelsGenerator`. It is merged into the generation result, where the models are published under
 * the `go.models` key.
 * @see GoModelGeneratorOutput
 */
export type GoModelsGeneratorOutput = {
  /**
   * The Go results of the generator, grouped under the `go` key.
   */
  go: {
    /**
     * The generated models, keyed by the ID of their schema. Each entry describes the Go type the schema maps to.
     */
    models: {
      /**
       * The result for the schema with the given ID. Schemas that get no file are included as well.
       */
      [schemaId: string]: GoModelGeneratorOutput;
    };
  };
};

/**
 * The result of generating the model for one schema.
 */
export type GoModelGeneratorOutput = {
  /** The type to use for the schema, e.g. a reference to the declared struct, or `[]string`. */
  type: go.Type<SourceBuilder>;
  /** The fields of the declared struct by property name, if the schema is declared as a struct. */
  fields?: { [propertyName: string]: GoModelFieldOutput };
};

/**
 * The result for one field of a generated struct.
 */
export type GoModelFieldOutput = {
  /** The name of the field. */
  name: string;
  /** The type of the field, a pointer if the property may be absent. */
  type: go.Type<SourceBuilder>;
};

/**
 * The context of the `GoModelsGenerator`, which holds the configuration and the output of the run. It also tracks the
 * packages that need the JSON helpers for additional properties.
 */
export type GoModelsGeneratorContext = OpenApiSchemasGenerationProviderContext<
  GoModelsGeneratorInput,
  GoModelsGeneratorOutput,
  GoModelsGeneratorConfig,
  GoModelGeneratorOutput
> & {
  /** The packages that need the JSON helpers for additional properties, by import path. */
  packagesWithAdditionalProperties: Map<string, GoPackageInfo>;
};

/**
 * The context for generating the model of one schema.
 */
export type GoModelGeneratorContext = GoModelsGeneratorContext & {
  /**
   * The schema to generate the model for.
   */
  schema: ApiSchema;
};
