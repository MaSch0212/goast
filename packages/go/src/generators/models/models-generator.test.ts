import { mkdtemp, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

import { afterEach, beforeEach, describe, expect, it } from 'vitest';

import { OpenApiGenerator } from '@goast/core';

import { GoModelsGenerator } from './models-generator.ts';
import type { GoModelsGeneratorConfig } from './models.ts';

let dir: string;

beforeEach(async () => {
  dir = await mkdtemp(join(tmpdir(), 'goast-go-models-'));
});

afterEach(async () => {
  await rm(dir, { recursive: true, force: true });
});

/** Generates the models for the schemas and returns the generated files by name. */
async function generate(schemas: Record<string, unknown>, config: Partial<GoModelsGeneratorConfig> = {}) {
  const specFile = join(dir, 'spec.json');
  await writeFile(
    specFile,
    JSON.stringify({ openapi: '3.0.3', info: { title: 'Test', version: '1' }, paths: {}, components: { schemas } }),
  );
  const outputDir = join(dir, 'out');
  const output = await new OpenApiGenerator({ outputDir, newLine: '\n' })
    .useType(GoModelsGenerator, config)
    .parseAndGenerate(specFile);

  const packageDir = join(outputDir, config.packagePath ?? 'api');
  const files: Record<string, string> = {};
  for (const name of await readdir(packageDir)) {
    files[name] = await readFile(join(packageDir, name), 'utf8');
  }
  return { output, files };
}

describe('GoModelsGenerator', () => {
  it('generates a struct with json tags, pointers for optional properties and docs', async () => {
    const { files } = await generate({
      Pet: {
        type: 'object',
        description: 'A pet.',
        required: ['id', 'name'],
        properties: {
          id: { type: 'string' },
          name: { type: 'string', description: 'The name.' },
          age: { type: 'integer', format: 'int32' },
          created_at: { type: 'string', format: 'date-time', nullable: true },
          tags: { type: 'array', items: { type: 'string' } },
        },
      },
    });

    expect(files['pet.go']).toBe(
      [
        '// Code generated by gOAst. DO NOT EDIT.',
        '',
        'package api',
        '',
        'import "time"',
        '',
        '// A pet.',
        'type Pet struct {',
        '\tID string `json:"id"`',
        '\t// The name.',
        '\tName      string     `json:"name"`',
        '\tAge       *int32     `json:"age,omitempty"`',
        '\tCreatedAt *time.Time `json:"created_at,omitempty"`',
        '\tTags      []string   `json:"tags,omitempty"`',
        '}',
        '',
      ].join('\n'),
    );
  });

  it('generates a string enum with constants and a validation method', async () => {
    const { files } = await generate({ Status: { type: 'string', enum: ['available', 'sold-out'] } });

    expect(files['status.go']).toContain(
      [
        'type Status string',
        '',
        'const (',
        '\tStatusAvailable Status = "available"',
        '\tStatusSoldOut   Status = "sold-out"',
        ')',
      ].join('\n'),
    );
    expect(files['status.go']).toContain('func (v Status) IsValid() bool {');
  });

  it('omits the validation method when it is disabled', async () => {
    const { files } = await generate({ Status: { type: 'string', enum: ['a'] } }, { addEnumValidation: false });

    expect(files['status.go']).not.toContain('IsValid');
  });

  it('keeps additional properties in a map with custom JSON methods and their helpers', async () => {
    const { files } = await generate({
      Labels: { type: 'object', properties: { name: { type: 'string' } }, additionalProperties: { type: 'string' } },
    });

    expect(files['labels.go']).toContain('AdditionalProperties map[string]string `json:"-"`');
    expect(files['labels.go']).toContain('func (v Labels) MarshalJSON() ([]byte, error) {');
    expect(files['labels.go']).toContain('func (v *Labels) UnmarshalJSON(data []byte) error {');
    expect(Object.keys(files)).toContain('additional_properties.go');
  });

  it('uses a map type for an object without fixed properties', async () => {
    const { files } = await generate({
      Game: {
        type: 'object',
        properties: { scores: { type: 'object', additionalProperties: { type: 'number' } } },
      },
    });

    expect(files['game.go']).toContain('Scores map[string]float64 `json:"scores,omitempty"`');
  });

  it('refers to a recursive property through a pointer', async () => {
    const { files } = await generate({
      Node: {
        type: 'object',
        required: ['next'],
        properties: { next: { $ref: '#/components/schemas/Node' } },
      },
    });

    expect(files['node.go']).toContain('Next *Node `json:"next"`');
  });

  it('returns the type and the fields of every schema', async () => {
    const { output } = await generate({
      Pet: { type: 'object', properties: { pet_id: { type: 'string' } } },
    });

    const pet = Object.values(output.go.models).find((x) => x.fields !== undefined)!;
    expect(pet.type).toMatchObject({ name: 'Pet', importPath: 'example.com/generated/api' });
    expect(pet.fields?.pet_id.name).toBe('PetID');
  });

  it('uses the configured package', async () => {
    const { files } = await generate(
      { Pet: { type: 'object', properties: { id: { type: 'string' } } } },
      { packagePath: 'internal/models' },
    );

    expect(files['pet.go']).toContain('package models');
  });
});
