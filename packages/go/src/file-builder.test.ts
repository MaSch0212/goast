import { describe, expect, it } from 'vitest';

import { go } from './ast/index.ts';
import { defaultGoGeneratorConfig, type GoGeneratorConfig } from './config.ts';
import { GoFileBuilder } from './file-builder.ts';

const options = { ...defaultGoGeneratorConfig, newLine: '\n' } as GoGeneratorConfig;

describe('GoFileBuilder', () => {
  it('writes the header, the package clause, the imports and the body', () => {
    const builder = new GoFileBuilder('api', 'example.com/generated/api', options);
    builder.append(go.typeDeclaration('Created', go.refs.time.time()));

    expect(builder.toString()).toBe(
      [
        '// Code generated by gOAst. DO NOT EDIT.',
        '',
        'package api',
        '',
        'import "time"',
        '',
        'type Created time.Time',
        '',
      ].join('\n'),
    );
  });

  it('omits the header when it is disabled', () => {
    const builder = new GoFileBuilder('api', undefined, { ...options, addGeneratedHeader: false });

    expect(builder.toString()).toBe('package api\n');
  });

  it('refers to a type of its own package without a qualifier', () => {
    const builder = new GoFileBuilder('api', 'example.com/generated/api', options);
    builder.append(
      go.reference('Pet', 'example.com/generated/api'),
      ' ',
      go.reference('Owner', 'example.com/x/models'),
    );

    expect(builder.toFragmentString()).toBe('Pet models.Owner');
    expect(builder.imports.imports.map((x) => x.path)).toEqual(['example.com/x/models']);
  });

  it('shares the imports with a fork', () => {
    const builder = new GoFileBuilder('api', undefined, options);
    builder.fork().append(go.refs.context.context());

    expect(builder.imports.imports.map((x) => x.path)).toEqual(['context']);
  });
});
