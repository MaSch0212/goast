import { type AppendParam, type AppendValue, isAppendValue, SourceBuilder, writeGeneratedFile } from '@goast/core';

import { GoNode } from './ast/node.ts';
import { defaultGoGeneratorConfig, type GoGeneratorConfig } from './config.ts';
import { GoImportCollection } from './import-collection.ts';

/**
 * The values that can be appended to a `GoFileBuilder`: Go nodes, and the additional values of the builder.
 * @template TAdditionalAppends The additional values, besides Go nodes, that the builder accepts.
 */
export type GoAppends<TAdditionalAppends> = GoNode<GoFileBuilder> | TAdditionalAppends;
/**
 * A parameter of an append method of a `GoFileBuilder`: a single value or builder function, or an array of them.
 * @template TBuilder The Go file builder type that the value is appended to.
 * @template TAdditionalAppends The additional values, besides Go nodes, that the builder accepts.
 * @see GoAppends
 */
export type GoAppendParam<TBuilder extends GoFileBuilder, TAdditionalAppends> = AppendParam<
  TBuilder,
  GoAppends<TAdditionalAppends>
>;

/**
 * Checks whether a value can be appended to a Go file builder: an append value, or a Go node.
 * @template TBuilder The Go file builder type that the value is appended to.
 * @param value The value to check.
 * @returns `true` if the value can be appended, otherwise `false`.
 */
export function isGoAppendValue<TBuilder extends GoFileBuilder>(value: unknown): value is AppendValue<TBuilder> {
  return isAppendValue(value) || value instanceof GoNode;
}

/**
 * The comment Go tools recognize generated files by, see
 * https://pkg.go.dev/cmd/go#hdr-Generate_Go_files_by_processing_source.
 */
export const goGeneratedFileHeader = '// Code generated by gOAst. DO NOT EDIT.';

/**
 * Builds the content of one Go source file. Besides the code, it collects the imports that the code needs, and
 * `toString` writes the header comment, the `package` clause, the imports and finally the code, in that order.
 *
 * Imports are collected while the code is written: a Go node that refers to a package calls `addImport`, which returns
 * the name to qualify the identifier with.
 *
 * @template TAdditionalAppends The additional values, besides Go nodes, that can be appended to the builder.
 * @see GoImportCollection
 * @see GoGeneratorConfig.addGeneratedHeader
 */
export class GoFileBuilder<TAdditionalAppends = never> extends SourceBuilder<GoAppends<TAdditionalAppends>> {
  /** The name in the `package` clause. */
  public readonly packageName: string;
  /**
   * The import path of the package, so references to its own declarations are not imported. `undefined` if the path is
   * not known, in which case no import is left out.
   */
  public readonly importPath: string | undefined;
  /** The imports of this file. `toString` writes them after the `package` clause. */
  public readonly imports: GoImportCollection;

  /**
   * Gets the options of this builder, which are the Go generator configuration that it was created with, or the
   * defaults.
   * @returns The options of this builder.
   */
  public override get options(): GoGeneratorConfig {
    return super.options as GoGeneratorConfig;
  }

  /**
   * Initializes a new instance of the GoFileBuilder class.
   * @param packageName The name in the `package` clause.
   * @param importPath The import path of the package, or `undefined` if it is not known.
   * @param options The Go generator configuration to use. Defaults to `defaultGoGeneratorConfig`.
   * @param imports The imports to collect into. Defaults to a new, empty collection. Passing a collection that is
   * shared with another builder makes both write the same imports.
   */
  constructor(packageName: string, importPath?: string, options?: GoGeneratorConfig, imports?: GoImportCollection) {
    super(options ?? (defaultGoGeneratorConfig as GoGeneratorConfig));
    this.packageName = packageName;
    this.importPath = importPath;
    this.imports = imports ?? new GoImportCollection();
  }

  /**
   * Creates an empty builder for a fragment of this file. The fragment shares the imports of this builder, so whatever
   * the fragment uses is imported in the file. Its content is read with `toFragmentString`.
   * @returns A new builder for the fragment, with the same package, options and imports.
   */
  public fork(): GoFileBuilder<TAdditionalAppends> {
    return new GoFileBuilder<TAdditionalAppends>(this.packageName, this.importPath, this.options, this.imports);
  }

  /**
   * Gets the content appended so far, without the header, `package` clause and imports.
   * @returns The code of this builder.
   */
  public toFragmentString(): string {
    return super.toString();
  }

  /**
   * Imports a package and returns the name to qualify its identifiers with. Nothing is imported, and `null` is
   * returned, when the path is the import path of this file, because its declarations are not qualified.
   * @param path The import path of the package, e.g. `net/http`.
   * @param packageName The name the package declares, if it differs from the last segment of its path.
   * @returns The name to qualify the identifiers of the package with, or `null` if it is the package of this file.
   */
  public addImport(path: string, packageName?: string): string | null {
    if (path === this.importPath) return null;
    return this.imports.addImport(path, packageName);
  }

  /** Clears the content of this builder, and the imports that it has collected. */
  public override clear(): void {
    super.clear();
    this.imports.clear();
  }

  /**
   * Gets the complete source of the file: the header comment if `addGeneratedHeader` is set, the `package` clause, the
   * imports, and the code. The code is rendered first, because writing it is what adds the imports.
   * @returns The source of the file.
   */
  public override toString(): string {
    // The body is rendered first, because writing it is what adds the imports.
    const body = super.toString();
    return new SourceBuilder(this.options)
      .if(this.options.addGeneratedHeader, (b) => b.appendLine(goGeneratedFileHeader).appendLine())
      .appendLine(`package ${this.packageName}`)
      .if(this.imports.hasImports, (b) => b.appendLine().append((b) => this.imports.writeTo(b)))
      .if(body.trim().length > 0, (b) => b.appendLine().append(body.trim()).appendLine())
      .toString();
  }

  /**
   * Writes the source of the file to disk, see `toString`. If the file already exists, the `existingFileBehavior`
   * option decides what happens: it is overwritten, skipped, written under a counted name, or an error is thrown.
   * @param filePath The path of the file to write.
   */
  public writeToFile(filePath: string): void {
    writeGeneratedFile(this.options, filePath, this.toString());
  }

  protected override appendSingle(value: GoAppendParam<this, TAdditionalAppends>): void {
    super.appendSingle(value);
    if (value instanceof GoNode) {
      value.write(this);
    }
  }
}
