import { type AppendParam, type AppendValue, isAppendValue, SourceBuilder, writeGeneratedFile } from '@goast/core';

import { GoNode } from './ast/node.ts';
import { defaultGoGeneratorConfig, type GoGeneratorConfig } from './config.ts';
import { GoImportCollection } from './import-collection.ts';

export type GoAppends<TAdditionalAppends> = GoNode<GoFileBuilder> | TAdditionalAppends;
export type GoAppendParam<TBuilder extends GoFileBuilder, TAdditionalAppends> = AppendParam<
  TBuilder,
  GoAppends<TAdditionalAppends>
>;

export function isGoAppendValue<TBuilder extends GoFileBuilder>(value: unknown): value is AppendValue<TBuilder> {
  return isAppendValue(value) || value instanceof GoNode;
}

/** The comment Go tools recognize generated files by, see https://pkg.go.dev/cmd/go#hdr-Generate_Go_files_by_processing_source. */
export const goGeneratedFileHeader = '// Code generated by gOAst. DO NOT EDIT.';

/** Builds the content of one Go source file. */
export class GoFileBuilder<TAdditionalAppends = never> extends SourceBuilder<GoAppends<TAdditionalAppends>> {
  /** The name in the `package` clause. */
  public readonly packageName: string;
  /** The import path of the package, so references to its own declarations are not imported. */
  public readonly importPath: string | undefined;
  public readonly imports: GoImportCollection;

  public override get options(): GoGeneratorConfig {
    return super.options as GoGeneratorConfig;
  }

  constructor(packageName: string, importPath?: string, options?: GoGeneratorConfig, imports?: GoImportCollection) {
    super(options ?? (defaultGoGeneratorConfig as GoGeneratorConfig));
    this.packageName = packageName;
    this.importPath = importPath;
    this.imports = imports ?? new GoImportCollection();
  }

  /** An empty builder for a fragment of this file: it shares the imports, so what the fragment uses is imported. */
  public fork(): GoFileBuilder<TAdditionalAppends> {
    return new GoFileBuilder<TAdditionalAppends>(this.packageName, this.importPath, this.options, this.imports);
  }

  /** The content appended so far, without the header, `package` clause and imports. */
  public toFragmentString(): string {
    return super.toString();
  }

  /**
   * Imports a package and returns the name to qualify its identifiers with, or `null` if it is the package of this
   * file.
   */
  public addImport(path: string, packageName?: string): string | null {
    if (path === this.importPath) return null;
    return this.imports.addImport(path, packageName);
  }

  public override clear(): void {
    super.clear();
    this.imports.clear();
  }

  public override toString(): string {
    // The body is rendered first, because writing it is what adds the imports.
    const body = super.toString();
    return new SourceBuilder(this.options)
      .if(this.options.addGeneratedHeader, (b) => b.appendLine(goGeneratedFileHeader).appendLine())
      .appendLine(`package ${this.packageName}`)
      .if(this.imports.hasImports, (b) => b.appendLine().append((b) => this.imports.writeTo(b)))
      .if(body.trim().length > 0, (b) => b.appendLine().append(body.trim()).appendLine())
      .toString();
  }

  public writeToFile(filePath: string): void {
    writeGeneratedFile(this.options, filePath, this.toString());
  }

  protected override appendSingle(value: GoAppendParam<this, TAdditionalAppends>): void {
    super.appendSingle(value);
    if (value instanceof GoNode) {
      value.write(this);
    }
  }
}
